import { createHash } from 'node:crypto';
import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { ExifTool } from 'exiftool-vendored';
import type { Plugin } from 'vite';

/**
 * The ExifTool arguments that strip an image's metadata. `-all=` clears
 * everything (EXIF — including GPS data —, XMP, IPTC, comments, thumbnails,
 * ...), then the display-affecting tags are copied back from the same file
 * (`-tagsfromfile @`): the ICC colour profile (removing it shifts colours)
 * and the EXIF Orientation (removing it displays rotated images unrotated).
 * `-overwrite_original` rewrites the file in place without leaving a backup.
 */
const STRIP_WRITE_ARGS = [
  '-tagsfromfile',
  '@',
  '-all=',
  '-icc_profile',
  '-Orientation',
  '-overwrite_original',
];

/**
 * The image formats ExifTool 13 can rewrite in place. JXL is excluded
 * because its metadata may be Brotli-compressed, which the vendored ExifTool
 * cannot process (and JXL files produced by `multiviewImagePlugin` carry no
 * metadata by construction). BMP and ICO are excluded because ExifTool cannot
 * write them.
 */
const IMAGE_EXTENSIONS = new Set([
  'avif',
  'gif',
  'heic',
  'heif',
  'jpeg',
  'jpg',
  'png',
  'tif',
  'tiff',
  'webp',
]);

const extensionOf = (fileName: string): string => path.extname(fileName).toLowerCase().slice(1);

/**
 * A Vite plugin that strips metadata (EXIF / XMP / IPTC / comments) from
 * every image in the build, so that no camera data (GPS coordinates,
 * timestamps, make/model, thumbnails, ...) ends up in the build output.
 *
 * Once the build has been written, the output directory is walked and every
 * image is stripped in place — which covers both images that flow through
 * the Vite pipeline (imported from code or MDX, including the variant files
 * generated by {@link multiviewImagePlugin} — the fallback variant of a
 * small source is a byte-for-byte copy of the source image and would
 * otherwise ship the source's EXIF data) and images copied from the
 * `public/` directory.
 *
 * The display of the images is preserved: the ICC colour profile and the
 * EXIF Orientation tag are retained, and the image data is never
 * re-encoded (ExifTool rewrites the file in place, leaving the compressed
 * stream untouched). Images that have no strippable metadata are left
 * byte-for-byte untouched.
 *
 * Only the build output is affected: source files on disk are never
 * modified, and the dev server serves the original files.
 *
 * Supported formats: JPEG, PNG, WebP, AVIF, HEIC / HEIF, TIFF and GIF.
 */
export const imagePrivacyPlugin = (): Plugin => {
  let exiftool: ExifTool | null = null;
  const getExiftool = () => {
    exiftool ??= new ExifTool();
    return exiftool;
  };

  // Stripped bytes depend only on the image's content, so cache per content
  // hash for the lifetime of the process (an image can appear in both the
  // client and the server build).
  const cache = new Map<string, Promise<Buffer>>();

  const strip = (source: Buffer, extension: string): Promise<Buffer> => {
    const key = createHash('sha256').update(source).digest('hex');
    let pending = cache.get(key);
    if (pending == null) {
      pending = (async () => {
        const tmpDir = await mkdtemp(path.join(os.tmpdir(), 'image-privacy-'));
        const tmpFile = path.join(tmpDir, `image.${extension}`);
        try {
          await writeFile(tmpFile, source);
          const result = await getExiftool().write(tmpFile, {}, { writeArgs: STRIP_WRITE_ARGS });
          if (result.updated + result.created > 0) return readFile(tmpFile);
          return source;
        } finally {
          await rm(tmpDir, { recursive: true, force: true });
        }
      })().catch((cause) => {
        cache.delete(key);
        throw new Error(
          `[@furtherland/vite-plugins] failed to strip metadata from an ${extension} image: ${
            cause instanceof Error ? cause.message : String(cause)
          }`,
        );
      });
      cache.set(key, pending);
    }
    return pending;
  };

  const walk = async (dir: string): Promise<string[]> => {
    const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
    const files: string[] = [];
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) files.push(...(await walk(fullPath)));
      else if (IMAGE_EXTENSIONS.has(extensionOf(entry.name))) files.push(fullPath);
    }
    return files;
  };

  return {
    name: '@furtherland/vite-plugins:image-privacy',

    buildStart() {
      if (exiftool?.ended) exiftool = null;
    },

    buildEnd() {
      if (exiftool == null) return;
      const instance = exiftool;
      exiftool = null;
      return instance.end();
    },

    async closeBundle() {
      const outDir = this.environment?.config?.build?.outDir;
      if (outDir == null) return;
      const files = await walk(outDir);
      await Promise.all(
        files.map(async (file) => {
          const source = await readFile(file);
          const stripped = await strip(source, extensionOf(file));
          if (!stripped.equals(source)) await writeFile(file, stripped);
        }),
      );
    },
  };
};
